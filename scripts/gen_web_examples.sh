#!/usr/bin/env bash
# Bundle examples/*.asm into web/examples.js so the browser demo works from file://
set -euo pipefail
ROOT="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
OUT="$ROOT/web/examples.js"

{
  echo "// AUTO-GENERATED by scripts/gen_web_examples.sh - do not edit."
  echo "window.TINYVM_EXAMPLES = {"
  for f in "$ROOT"/examples/*.asm; do
    name="$(basename "$f" .asm)"
    printf '  %s: `' "$name"
    sed -e 's/\\/\\\\/g' -e 's/`/\\`/g' -e 's/\${/\\${/g' "$f"
    echo '`,'
  done
  echo "};"
} > "$OUT"
echo "wrote $OUT"
